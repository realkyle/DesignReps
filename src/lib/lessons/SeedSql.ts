import { z } from "zod";

import type { Lesson } from "./Lesson";

/** A track as declared in `content/tracks.json`. */
export const trackSchema = z.strictObject({
  slug: z.string().regex(/^[a-z0-9]+(-[a-z0-9]+)*$/),
  title: z.string().trim().min(1).max(80),
  description: z.string().trim().min(1).max(300),
  position: z.number().int().positive(),
});

export type TrackDefinition = z.infer<typeof trackSchema>;

/** One track and its validated lessons. */
export interface TrackContent {
  track: TrackDefinition;
  lessons: readonly Lesson[];
}

/**
 * Turns validated content into idempotent SQL for `supabase/seed.sql`.
 *
 * Upserts by natural key (track slug; track + lesson slug), so running the
 * seed again updates lessons in place and keeps their IDs. That matters
 * because `progress` rows point at lesson IDs.
 *
 * Pure: no file or database access, so it's unit-tested directly.
 */
export class SeedSql {
  private constructor(private readonly tracks: readonly TrackContent[]) {}

  static from(tracks: readonly TrackContent[]): SeedSql {
    return new SeedSql(tracks);
  }

  toSql(): string {
    const parts = [
      "-- GENERATED by `npm run seed:build` from content/. Do not edit by hand.",
      "-- Applied with `npm run seed:push` (live) or `npx supabase db reset` (local).",
      "",
    ];
    for (const { track, lessons } of this.tracks) {
      parts.push(SeedSql.trackUpsert(track));
      for (const lesson of lessons) parts.push(SeedSql.lessonUpsert(track.slug, lesson));
    }
    return parts.join("\n") + "\n";
  }

  private static trackUpsert(track: TrackDefinition): string {
    return [
      "insert into public.tracks (slug, title, description, position, is_published)",
      `values (${SeedSql.text(track.slug)}, ${SeedSql.text(track.title)}, ${SeedSql.text(track.description)}, ${track.position}, true)`,
      "on conflict (slug) do update set",
      "  title = excluded.title, description = excluded.description,",
      "  position = excluded.position, is_published = excluded.is_published;",
      "",
    ].join("\n");
  }

  private static lessonUpsert(trackSlug: string, lesson: Lesson): string {
    const row = lesson.toDatabaseRow();
    return [
      "insert into public.lessons (track_id, slug, title, kind, position, content, is_published)",
      `select t.id, ${SeedSql.text(row.slug)}, ${SeedSql.text(row.title)}, ${SeedSql.text(row.kind)}, ${row.position},`,
      `       ${SeedSql.text(JSON.stringify(row.content))}::jsonb, true`,
      `from public.tracks t where t.slug = ${SeedSql.text(trackSlug)}`,
      "on conflict (track_id, slug) do update set",
      "  title = excluded.title, kind = excluded.kind, position = excluded.position,",
      "  content = excluded.content, is_published = excluded.is_published;",
      "",
    ].join("\n");
  }

  /** A SQL string literal: single quotes doubled, so content can't break out of it. */
  static text(value: string): string {
    return `'${value.replaceAll("'", "''")}'`;
  }
}
